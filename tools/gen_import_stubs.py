#!/usr/bin/env python3
"""Generate logging no-op stubs for kernel/xam imports the runtime does not implement.

usage: gen_import_stubs.py <ppc_func_mapping.cpp> <runtime/src> <export tables...> > import_stubs.cpp

Import symbols in the recompiled code are weak functions named after their export. Every
export name used by the game that has no FA_IMPORT(name) in runtime/src gets a stub that
logs the first call and returns 0, so a missing import shows up in the log instead of
silently doing nothing.
"""
import os, re, sys

mapping, src_dir, *tables = sys.argv[1:]
exports = set()
for t in tables:
    exports |= set(re.findall(r"XE_EXPORT\(\w+,\s*0x[0-9A-Fa-f]+,\s*(\w+),\s*kFunction\)", open(t).read()))
used = set(re.findall(r"\{\s*0x[0-9A-Fa-f]+,\s*(?:__imp__)?(\w+)\s*\}", open(mapping).read()))
used = {n for n in used if n in exports}

implemented = set()
for root, _, files in os.walk(src_dir):
    for f in files:
        if f.endswith(".cpp"):
            implemented |= set(re.findall(r"FA_IMPORT\((\w+)\)", open(os.path.join(root, f)).read()))
            implemented |= set(re.findall(r"PPC_FUNC\((\w+)\)", open(os.path.join(root, f)).read()))

print('#include "fa/rt/import.hpp"\n#include <cstdio>\n')
print("// Generated by tools/gen_import_stubs.py. Do not edit.")
print('#define FA_STUB(n) PPC_FUNC(__imp__##n) { static fa::rt::ImportStat fa_stat{#n " (stub)"}; \\')
print("    if (fa_stat.calls.fetch_add(1, std::memory_order_relaxed) == 0) { \\")
print('    std::fprintf(stderr, "unimplemented import: " #n " (r3=%08X r4=%08X r5=%08X)\\n", ctx.r3.u32, ctx.r4.u32, ctx.r5.u32); } \\')
print("    ctx.r3.u64 = 0; } \\")
print("    PPC_FUNC(n) { __imp__##n(ctx, base); }\n")
missing = sorted(used - implemented)
for n in missing:
    print(f"FA_STUB({n})")
sys.stderr.write(f"{len(used)} imports used, {len(used & implemented)} implemented, {len(missing)} stubbed\n")
